// Pure helpers shared by the Edge Function and the Node tests. No Deno/Supabase imports here.

/** Opens within this window after registration are the sender's own compose window loading the pixel. */
export const GRACE_MS = 15_000;
/** A second open this soon after a counted one is the same open (proxies often fetch twice). */
export const DEDUPE_MS = 10_000;
/** How long a "the sender is looking at this message" ping suppresses opens, before and after. */
export const SELF_WINDOW_MS = 20_000;

/** 1x1 transparent GIF. */
export const PIXEL = Uint8Array.from(
  atob("R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7"),
  (c) => c.charCodeAt(0),
);

/**
 * Split a request path into a route. Supabase may or may not keep the function
 * name in the path, so everything up to and including "/track" is dropped.
 */
export function parseRoute(method, pathname) {
  const idx = pathname.indexOf("/track");
  const rest = idx >= 0 ? pathname.slice(idx + "/track".length) : pathname;
  const parts = rest.split("/").filter(Boolean);

  if (method === "GET" && parts[0] === "o" && parts[1]) {
    return { name: "open", id: parts[1].replace(/\.(gif|png)$/i, "") };
  }
  if (method === "GET" && parts[0] === "c" && parts[1] && parts[2] !== undefined) {
    const n = Number.parseInt(parts[2], 10);
    return Number.isInteger(n) && n >= 0 ? { name: "click", id: parts[1], n } : { name: "notFound" };
  }
  if (parts[0] === "api") {
    const [, resource, id] = parts;
    if (resource === "ping" && method === "GET") return { name: "ping" };
    if (resource === "emails" && !id && method === "GET") return { name: "listEmails" };
    if (resource === "emails" && !id && method === "POST") return { name: "createEmail" };
    if (resource === "emails" && id && method === "PATCH") return { name: "updateEmail", id };
    if (resource === "emails" && id && method === "DELETE") return { name: "deleteEmail", id };
    if (resource === "self" && id && method === "POST") return { name: "selfView", id };
  }
  return { name: "notFound" };
}

/** Tracking ids are generated by the extension: 16 random bytes, base64url. */
export function isValidId(id) {
  return typeof id === "string" && /^[A-Za-z0-9_-]{16,64}$/.test(id);
}

/**
 * Decide whether an open should count.
 * @param {{created_at: string, suppress_until?: string|null}} email
 * @param {string|null} lastCountedOpenAt ISO timestamp of the previous counted open
 * @param {number} now epoch ms
 */
export function classifyOpen(email, lastCountedOpenAt, now) {
  if (now - Date.parse(email.created_at) < GRACE_MS) return { counted: false, reason: "grace" };
  if (email.suppress_until && now <= Date.parse(email.suppress_until)) return { counted: false, reason: "self" };
  if (lastCountedOpenAt && now - Date.parse(lastCountedOpenAt) < DEDUPE_MS) {
    return { counted: false, reason: "duplicate" };
  }
  return { counted: true, reason: null };
}

/** Best-effort guess of the mail client from the User-Agent of the pixel request. */
export function guessClient(ua = "") {
  if (/GoogleImageProxy/i.test(ua)) return "Gmail";
  if (/YahooMailProxy/i.test(ua)) return "Yahoo Mail";
  if (/Outlook|Microsoft Office|ms-office/i.test(ua)) return "Outlook";
  if (/Thunderbird/i.test(ua)) return "Thunderbird";
  if (/iPhone|iPad/i.test(ua)) return "iOS Mail";
  if (/Macintosh/i.test(ua) && /AppleWebKit/i.test(ua) && !/Chrome|Safari/i.test(ua)) return "Apple Mail";
  if (/Android/i.test(ua)) return "Android";
  if (/Chrome|Firefox|Safari|Edg/i.test(ua)) return "Web browser";
  return "Unknown";
}

/** Only redirect to http(s) URLs that were registered for this email. */
export function resolveLink(links, n) {
  const url = Array.isArray(links) ? links[n] : undefined;
  if (typeof url !== "string") return null;
  try {
    const u = new URL(url);
    return u.protocol === "http:" || u.protocol === "https:" ? u.toString() : null;
  } catch {
    return null;
  }
}

/** Merge an email row with its counted events into what the extension displays. */
export function summarize(email, events) {
  const mine = events
    .filter((e) => e.email_id === email.id && e.counted)
    .sort((a, b) => Date.parse(a.created_at) - Date.parse(b.created_at));
  const opens = mine.filter((e) => e.kind === "open");
  const clicks = mine.filter((e) => e.kind === "click");
  const { suppress_until: _ignored, ...rest } = email;
  return {
    ...rest,
    open_count: opens.length,
    first_opened_at: opens[0]?.created_at ?? null,
    last_opened_at: opens.at(-1)?.created_at ?? null,
    click_count: clicks.length,
    last_clicked_at: clicks.at(-1)?.created_at ?? null,
    events: mine.slice(-50).map((e) => ({
      kind: e.kind,
      at: e.created_at,
      client: e.client,
      url: e.url ?? null,
    })),
  };
}

/** Fields the extension may change with PATCH /api/emails/:id. */
export const PATCHABLE = ["thread_id", "replied_at", "reply_from", "status", "follow_up_at", "notes", "subject"];

export function pickPatch(body) {
  const out = {};
  for (const key of PATCHABLE) if (key in (body ?? {})) out[key] = body[key];
  if ("status" in out && !["active", "done", "archived"].includes(out.status)) delete out.status;
  return out;
}
